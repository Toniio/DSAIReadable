import { defineConfig, globalIgnores } from "eslint/config"
import nextVitals from "eslint-config-next/core-web-vitals"
import nextTs from "eslint-config-next/typescript"
import betterTailwindcss from "eslint-plugin-better-tailwindcss"
import { createRequire } from "node:module"

// eslint-plugin-react 7.37 detects the React version through
// context.getFilename(), which ESLint 10 removed: `version: "detect"` crashes
// every react/* rule. Reading the installed version gives the same answer
// without the removed API.
const reactVersion = createRequire(import.meta.url)(
  "react/package.json"
).version

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  { settings: { react: { version: reactVersion } } },
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Build artefacts and vendored deps: linting them reports on generated
    // code nobody edits.
    "packages/*/dist/**",
    "packages/*/node_modules/**",
    "mcp-server/node_modules/**",
  ]),
  {
    // Tailwind lockdown, second half: app/globals.css removes the default
    // colours, radii and shadows, so bg-red-500 generates no CSS; this makes
    // the same class an error before it ships. Unknown = not generated by the
    // real stylesheet, design-system tokens included.
    files: ["{app,components,lib,hooks}/**/*.{ts,tsx}"],
    plugins: { "better-tailwindcss": betterTailwindcss },
    settings: { "better-tailwindcss": { entryPoint: "app/globals.css" } },
    rules: {
      "better-tailwindcss/no-unknown-classes": [
        "error",
        {
          // Hooks, not utilities: sonner styles `.toaster`, and shadcn's
          // input-otp targets `.cn-input-otp` from its own stylesheet.
          ignore: ["^toaster$", "^cn-input-otp$"],
        },
      ],
      // A disabled state reads opacity.disabled, not Tailwind's opacity
      // scale: `disabled:opacity-50` would keep the look and drop the token.
      "better-tailwindcss/no-restricted-classes": [
        "error",
        {
          restrict: [
            {
              pattern: "^(.*disabled[^:]*:)opacity-\\d+$",
              message:
                "A disabled state uses the opacity.disabled token: write $1opacity-disabled.",
              fix: "$1opacity-disabled",
            },
          ],
        },
      ],
    },
  },
  {
    // CommonJS tooling scripts: require() is the correct syntax there.
    files: ["**/*.cjs"],
    rules: { "@typescript-eslint/no-require-imports": "off" },
  },
])

export default eslintConfig
